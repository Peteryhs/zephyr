// Independent single-scattering bake. No reference table or shader is used.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const R=6371, TOP=R+80, observer=[0,R+.12,0], HR=8, HM=1.2;
const betaR=[.0058,.0135,.0331], wavelengths=[.680,.550,.440];
const lanes=[.03,.08,.15,.30,.60,1.20], views=[65,30,10,3], PI=Math.PI;
const dot=(a,b)=>a.reduce((v,x,i)=>v+x*b[i],0);
const point=(o,d,t)=>o.map((x,i)=>x+d[i]*t);
const height=p=>Math.hypot(...p)-R;
function sphere(o,d,r) { const b=dot(o,d),c=dot(o,o)-r*r,q=b*b-c; return q<0 ? null : [-b-Math.sqrt(q),-b+Math.sqrt(q)]; }
function depth(p,sun) {
  const ground=sphere(p,sun,R);
  if(ground&&ground[0]>0)return null;
  const end=sphere(p,sun,TOP)[1];
  let ray=0,mie=0;
  for(let i=0;i<12;i++) {
    const h=height(point(p,sun,end*(i+.5)/12));
    ray+=Math.exp(-h/HR)*end/12; mie+=Math.exp(-h/HM)*end/12;
  }
  return [ray,mie];
}
function sample(e,v,aod) {
  const er=e*PI/180,vr=v*PI/180;
  const sun=[Math.cos(er),Math.sin(er),0];
  const view=[Math.cos(vr)*.6,Math.sin(vr),Math.cos(vr)*.8];
  const mu=dot(sun,view),g=.76;
  const phaseR=3*(1+mu*mu)/(16*PI);
  const phaseM=(1-g*g)/(4*PI*(1+g*g-2*g*mu)**1.5);
  const betaM=wavelengths.map(w=>aod/HM*(.55/w)**1.1);
  const end=sphere(observer,view,TOP)[1];
  let dr=0,dm=0,rgb=[0,0,0];
  const count=36;
  for(let i=0;i<count;i++) {
    // Quadratic placement resolves the low aerosol layer near the observer.
    const lo=(i/count)**2*end,hi=((i+1)/count)**2*end,step=hi-lo;
    const p=point(observer,view,(lo+hi)/2),h=height(p);
    const rr=Math.exp(-h/HR),mm=Math.exp(-h/HM),sd=depth(p,sun);
    if(sd) for(let c=0;c<3;c++) {
      const tau=betaR[c]*(dr+.5*rr*step+sd[0])+betaM[c]*(dm+.5*mm*step+sd[1]);
      rgb[c]+=120000*Math.exp(-tau)*(betaR[c]*rr*phaseR+betaM[c]*mm*phaseM)*step;
    }
    dr+=rr*step; dm+=mm*step;
  }
  // Empirical diffuse/multiple scattering closure. It fills the Earth's shadow
  // without an arbitrary screen-space gradient and is versioned with the bake.
  const twilight=Math.exp(Math.min(e,0)/1.45), daylight=Math.max(0,Math.sin(er));
  const diffuse=(.12+.22*aod)*twilight*(.35+.65*Math.sqrt(daylight));
  const cool=[.42,.66,1];
  // Extinguish the empirical closure once the lower atmosphere is fully in
  // shadow. The display/night floors are applied later, in their own stages.
  const cut=Math.max(0,Math.min(1,(-e-8)/4)),nightCut=1-cut*cut*(3-2*cut);
  rgb=rgb.map((x,c)=>(x*(1+diffuse)+cool[c]*85*twilight*(1+.7/Math.max(.15,Math.sin(vr))))*nightCut);
  return rgb.map(x=>Number(x.toPrecision(8)));
}
function disk(e,aod) {
  const z=Math.max(.5,e),air=Math.min(40,1/(Math.sin(z*PI/180)+.15*(z+3.885)**-1.253));
  const tau=betaR.map((b,i)=>b*HR+aod*(.55/wavelengths[i])**1.1);
  return tau.map(t=>Number(Math.exp(-(t-tau[0])*air*.65).toPrecision(8)));
}
const sky=[],body=[];
for(const aod of lanes) {
  for(let e=-18;e<=90;e++) for(const v of views) sky.push(...sample(e,v,aod));
  for(let e=-2;e<=90;e+=2)body.push(...disk(e,aod));
}
const data={version:'independent-single-scattering-1',lanes,framing:views,sky,body};
await writeFile(fileURLToPath(new URL('../sky/atmosphere-data.js',import.meta.url)),`// Generated by npm run bake. Independent atmospheric data.\nexport default ${JSON.stringify(data)};\n`);
console.log(`Baked ${sky.length} sky channels and ${body.length} body channels.`);
