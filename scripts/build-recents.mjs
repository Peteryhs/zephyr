/* Inline recents/engine.js into plugin.js, as scripts/build-sky.mjs does for sky/.
   The plugin ships as one file, the logic lives in a module the tests import
   directly, and `npm run check` fails if the two ever disagree.

     node scripts/build-recents.mjs                                              */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const PLUGIN = join(root, 'plugin.js')
const START = '/* ── recents/engine.js '
const END = '/* ── end recents/engine.js ── */'

const source = (await readFile(join(root, 'recents', 'engine.js'), 'utf8')).trim()
const names = [...source.matchAll(/^export\s+(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1])
if (!names.length) throw new Error('recents/engine.js exports nothing')
const body = source.replace(/^export\s+(?=(const|let|function|class)\b)/gm, '')

const head = `${START}${'─'.repeat(40)} generated by scripts/build-recents.mjs, edit recents/engine.js instead */`
const block = `${head}\nconst RECENTS = (() => {\n${body}\nreturn { ${names.join(', ')} }\n})()\n${END}`

let plugin = await readFile(PLUGIN, 'utf8')
const from = plugin.indexOf(START)
if (from >= 0) {
  const to = plugin.indexOf(END, from)
  if (to < 0) throw new Error('the recents block has no end marker')
  plugin = plugin.slice(0, from) + block + plugin.slice(to + END.length)
} else {
  const anchor = '// ══ §9 PLUGIN REGISTRATION'
  const at = plugin.indexOf(anchor)
  if (at < 0) throw new Error('§9 anchor not found in plugin.js')
  const lineStart = plugin.lastIndexOf('\n', at) + 1
  plugin = plugin.slice(0, lineStart) + block + '\n\n' + plugin.slice(lineStart)
}
await writeFile(PLUGIN, plugin)
console.log(`recents engine: ${block.length} bytes, ${names.length} exports`)
