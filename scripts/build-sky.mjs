/* Generate the sky engine that ships inside plugin.js §6, from the sources in
   sky/. Run it after any edit to sky/:

     node scripts/build-sky.mjs

   It writes the block in place, so `git status` shows plugin.js change only when
   the sources actually changed. */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(root, 'sky')
const PLUGIN = join(root, 'plugin.js')

/* dependency order: helpers, clock, grade, the baked table, the sampler, the
   frame evaluator, then the shader text. sky/renderer.js is the reference GL
   driver for the standalone build and the tests: the plugin's adapter drives GL
   itself, so it is not inlined. */
const ORDER = [
  'math.js', 'clock.js', 'grade.js',
  ['atmosphere-data.js', 'data'], ['atmosphere-calibration.js', 'calibration'],
  'atmosphere.js', 'engine.js', 'shaders.js',
]

const strip = (code, defaultName = '__default') => code.split('\n')
  .filter(l => !/^\s*import\s/.test(l)).join('\n')
  .replace(/^export\s+\{[^}]*\}\s+from\s+'[^']*';?\s*$/gm, '')
  .replace(/^export\s+\{[^}]*\};?\s*$/gm, '')   // bare re-export of locals
  .replace(/^export\s+default\s+/gm, `const ${defaultName} = `)
  .replace(/^export\s+(?=(const|let|var|function|class|async)\b)/gm, '')

const decls = {}
const parts = []
for (const entry of ORDER) {
  const [file, defaultName] = Array.isArray(entry) ? entry : [entry]
  const code = strip(await readFile(join(SRC, file), 'utf8'), defaultName)
  for (const m of code.matchAll(/^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (decls[m[1]]) throw new Error(`duplicate declaration ${m[1]}: ${decls[m[1]]} and ${file}`)
    decls[m[1]] = file
  }
  parts.push(`/* ── sky/${file} ${'─'.repeat(Math.max(1, 62 - file.length))} */\n${code.trim()}`)
}
parts.push(`/* ── sky/adapter.js ────────────────────────────────────────────────────────── */\n${(await readFile(join(SRC, 'adapter.js'), 'utf8')).trim()}`)

const banner = `/* ============================================================================
   ZEPHYR SKY ENGINE — an independent implementation of the dynamic sky.

   No third-party sky code lives here. Every equation, gate and pixel stage
   comes from docs/rebuild-specification.md, written from the observed
   behaviour of a reference module, and the atmospheric table is an
   independent Rayleigh/Mie bake (scripts/bake-atmosphere.mjs).

   GENERATED by scripts/build-sky.mjs from sky/*.js — do not hand-edit.
   Edit the sources in sky/ and re-run the build.
   ============================================================================ */`

const block = `${banner}
const SKY_ENGINE = (() => {
${parts.join('\n\n')}
})();`

let plugin = await readFile(PLUGIN, 'utf8')
const start = plugin.indexOf(`/* ============================================================================
   ZEPHYR SKY ENGINE`)
if (start < 0) throw new Error('the engine banner is not in plugin.js')
const marker = '\n})();'
const end = plugin.indexOf(marker, start)
if (end < 0) throw new Error('the engine block has no closing })();')
const endAt = end + marker.length
if (!plugin.slice(start, endAt).includes('const SKY_ENGINE = (() => {')) throw new Error('that block is not the engine')

plugin = plugin.slice(0, start) + block + plugin.slice(endAt)
await writeFile(PLUGIN, plugin)
console.log(`sky engine: ${block.length} bytes from ${ORDER.length} modules + adapter (${Object.keys(decls).length} declarations)`)
